// Generates the PJSIP config for trunks (IP numbers) and extensions stored in the panel.
// Written to ASTERISK_PJSIP_FILE (included from pjsip.conf) and reloaded through ARI.
const fs = require('fs');
const { db } = require('../db');
const cfg = require('../config');

const clean = (v) => String(v ?? '').replace(/[\r\n;]/g, '');

function generatePjsip() {
  const out = ['; Generated by IP Call Panel - do not edit by hand; changes are overwritten.', ''];
  for (const t of db.prepare('SELECT * FROM ip_numbers WHERE enabled = 1 ORDER BY id').all()) {
    const n = `trunk${t.id}`;
    const user = clean(t.username || t.number);
    const host = `${clean(t.sip_server)}:${Number(t.port) || 5060}`;
    out.push(
      `; ${clean(t.number)} (user #${t.user_id})`,
      `[${n}-auth]`, 'type=auth', 'auth_type=userpass', `username=${user}`, `password=${clean(t.password)}`, '',
      `[${n}-reg]`, 'type=registration', `transport=transport-${t.transport === 'tcp' ? 'tcp' : 'udp'}`,
      `outbound_auth=${n}-auth`, `server_uri=sip:${host}`, `client_uri=sip:${user}@${host}`,
      `contact_user=${user}`, 'retry_interval=60', 'forbidden_retry_interval=300', 'expiration=300', 'line=yes', `endpoint=${n}`, '',
      `[${n}]`, 'type=aor', `contact=sip:${host}`, 'qualify_frequency=60', '',
      `[${n}]`, 'type=endpoint', `transport=transport-${t.transport === 'tcp' ? 'tcp' : 'udp'}`, 'context=ipcall-inbound',
      'disallow=all', 'allow=ulaw,alaw,gsm', `outbound_auth=${n}-auth`, `aors=${n}`, `from_user=${user}`,
      `from_domain=${clean(t.sip_server)}`, 'direct_media=no', 'rtp_symmetric=yes', 'force_rport=yes', 'rewrite_contact=yes',
      `set_var=IPCALL_TRUNK=${t.id}`, '',
      `[${n}-identify]`, 'type=identify', `endpoint=${n}`, `match=${clean(t.sip_server)}`, '',
    );
  }
  for (const x of db.prepare('SELECT * FROM extensions ORDER BY sip_number').all()) {
    const n = clean(x.sip_number);
    out.push(
      `; extension ${n} (user #${x.user_id}) ${clean(x.agent_name)}`,
      `[${n}]`, 'type=auth', 'auth_type=userpass', `username=${n}`, `password=${clean(x.password)}`, '',
      `[${n}]`, 'type=aor', 'max_contacts=1', 'remove_existing=yes', 'qualify_frequency=30', '',
      `[${n}]`, 'type=endpoint', 'transport=transport-udp', 'context=ipcall-agents', 'disallow=all', 'allow=ulaw,alaw,opus',
      `auth=${n}`, `aors=${n}`, 'direct_media=no', 'rtp_symmetric=yes', 'force_rport=yes', 'rewrite_contact=yes', '',
    );
  }
  return out.join('\n');
}

/** Write the config file and ask Asterisk to reload PJSIP. Returns a status message. */
async function applyPjsip(driver) {
  if (!cfg.asterisk.pjsipFile) return 'ASTERISK_PJSIP_FILE is not set; copy the generated config manually.';
  fs.writeFileSync(cfg.asterisk.pjsipFile, generatePjsip());
  if (driver?.ari) {
    await driver.ari('PUT', '/asterisk/modules/res_pjsip.so');
    return 'Config written and PJSIP reloaded.';
  }
  return 'Config written. Reload PJSIP in Asterisk (module reload res_pjsip.so).';
}

module.exports = { generatePjsip, applyPjsip };
